    <h2 id="evidence-title">那颗没有熄灭的光，<br />能证明什么？</h2>
    <p class="lead">
      一片变暗的城市里，常会留下孤立的光岛。它可能来自医院、机场或主干道，
      也可能来自车辆、火焰或临时照明。卫星只完成证据链的第一步。
    </p>
  </div>

  <ol class="evidence__ladder">
    <li>
      <span>01 · 卫星观测</span>
      <h3>这里仍有光。</h3>
      <p>能确认某个约 500 米区域仍有夜间辐亮度，或相对基准没有完全变暗。</p>
      <strong>已观察</strong>
    </li>
    <li>
      <span>02 · 地理对照</span>
      <h3>这里是什么？</h3>
      <p>要把光点对应到医院、机场或道路，必须加入可靠的设施位置和道路资料。</p>
      <strong>待核对</strong>
    </li>
    <li>
      <span>03 · 地面核验</span>
      <h3>电从哪里来？</h3>
      <p>电网、备用发电机或临时光源只能由设施记录、现场报道或传感器进一步确认。</p>
      <strong>待证明</strong>
    </li>
  </ol>

  <p class="evidence__rule">
    所以，本故事会说“某处仍有光”，不会仅凭一颗像素写成“医院有电”。
  </p>
