      <h3>恒星</h3>
      <p>250 条记录来自 Bright Star Catalogue V/50，固定 J2000 天区：RA 72°—94°、Dec −11.5°—23°、V ≤ 6.5。</p>
    </div>
    <div>
      <h3>时间</h3>
      <p>天空辉光按 Globe at Night 研究的全球 9.6% 年复合增长情景计算；250 与约 100 是论文示例端点，中间阈值是编辑视觉插值。</p>
    </div>
    <div>
      <h3>地点</h3>
      <p>2016 World Atlas 使用 2014 夜间卫星资料。地点是模型分档，不是现场预报；本版未使用局部 Globe at Night 观测校验。</p>
    </div>
    <div>
      <h3>照明</h3>
      <p>五项原则来自 DarkSky International 与 Illuminating Engineering Society。没有完整物理模型时不输出恢复星数。</p>
